/**
 * 取某一年的完整城市数据（返回全新数组，不污染基础数据）。
 * @param {number} year 年份，如 2024 / 2025 / 2026
 */
export function getPopulationByYear(year) {
    const map = VALUES[year];
    if (!map) return cities.map((c) => ({ ...c }));
    return cities.map((c) => ({
        ...c,
        value: map[c.name] != null ? map[c.name] : c.value
    }));
}
